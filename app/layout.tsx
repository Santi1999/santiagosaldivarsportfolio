import type { Metadata, Viewport } from "next";
import { Montserrat, Space_Grotesk } from "next/font/google";
import Navbar from "@/components/Navbar";
import { THEME_DIAL_BOOT } from "@/lib/themeDial";
import "./globals.css";

const montserrat = Montserrat({
  variable: "--font-montserrat",
  subsets: ["latin"],
  style: ["normal", "italic"],
});

const spaceGrotesk = Space_Grotesk({
  variable: "--font-space-grotesk",
  subsets: ["latin"],
});

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

// Deliberately NO themeColor, here or anywhere else. iOS 26 Safari ignores
// it for the status strip, and a static value would only be a second source
// of truth to keep in step with the theme dial.
//
// What does tint the top strip is the sticky header's own background-color —
// see the note on <header> in components/Navbar.tsx.
//
// viewportFit only takes effect in standalone mode (needs a manifest); in a
// browser tab env(safe-area-inset-top) is 0. Kept because it's correct and
// costs nothing, not because it does anything here today.
export const viewport: Viewport = {
  viewportFit: "cover",
};

export default function RootLayout({ children }: LayoutProps<"/">) {
  return (
    <html
      lang="en"
      suppressHydrationWarning
      className={`${montserrat.variable} ${spaceGrotesk.variable} h-full antialiased`}
    >
      <head>
        {/* Restores the saved dial position before first paint, per Next's
            documented anti-flash pattern — runs synchronously during HTML
            parsing, before React exists, so someone who left the dial on
            dark never gets a frame of white. suppressHydrationWarning on
            <html> is required because this mutates its style/attributes
            ahead of hydration; see components/ThemeDial.tsx for the matching
            dev-mode (Strict Mode remount) re-apply. */}
        <script dangerouslySetInnerHTML={{ __html: THEME_DIAL_BOOT }} />
      </head>
      <body className="min-h-full flex flex-col">
        <Navbar />
        {children}
      </body>
    </html>
  );
}
